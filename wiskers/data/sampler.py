"""
Samplers for drawing trajectory chunks from a ReplayBuffer.

Designed to be instantiated directly in Hydra configs via `_target_`:

    # in configs/dataset/breakout.yaml
    sampler:
      _target_: wiskers.data.sampler.UniformChunkSampler
      num_steps: 50
"""

import math
import random
from abc import ABC, abstractmethod

from wiskers.data.buffer import ReplayBuffer
from wiskers.data.episode import Episode


class TrajectorySampler(ABC):
    """
    Abstract base class for trajectory samplers.

    Subclasses define how valid episodes are weighted via ``_episode_weights``.
    """

    def __init__(self, num_steps: int = 50) -> None:
        if num_steps < 1:
            raise ValueError(f"num_steps must be >= 1, got {num_steps}")
        self.num_steps = num_steps

    @abstractmethod
    def _episode_weights(
        self,
        valid_episodes: list[tuple[int, Episode]],
        total_episodes: int,
    ) -> list[float]:
        """Compute unnormalized sampling weights for each valid ``(buffer_idx, episode)``."""
        ...

    def sample(self, buffer: ReplayBuffer, batch_size: int) -> list[Episode]:
        """
        Sample ``batch_size`` episode chunks from ``buffer``.

        Args:
            buffer: The ReplayBuffer to sample from.
            batch_size: Number of chunks to sample.

        Returns:
            List of Episode chunks of ``num_steps`` transitions (with ``num_steps + 1`` observations).
        """
        if buffer.is_empty:
            raise RuntimeError("Cannot sample from an empty ReplayBuffer.")

        all_episodes = buffer.episodes
        valid = [(i, ep) for i, ep in enumerate(all_episodes) if len(ep) >= self.num_steps]
        if not valid:
            raise RuntimeError(
                f"Cannot sample chunks of length {self.num_steps}: "
                f"no episodes in buffer have length >= {self.num_steps}."
            )

        weights = self._episode_weights(valid, total_episodes=len(all_episodes))
        chosen = random.choices([ep for _, ep in valid], weights=weights, k=batch_size)
        chunks: list[Episode] = []
        for episode in chosen:
            start = random.randint(0, len(episode) - self.num_steps)
            chunks.append(episode.slice(start, start + self.num_steps))
        return chunks

    def __call__(self, buffer: ReplayBuffer, batch_size: int) -> list[Episode]:
        return self.sample(buffer, batch_size)


class UniformChunkSampler(TrajectorySampler):
    """
    Uniform transition-level chunk sampler.

    Samples contiguous chunks of fixed length `num_steps`. Episodes are chosen
    with probability proportional to their number of valid start positions:

        weight(ep) = len(ep) - num_steps + 1

    And the start index within the chosen episode is drawn uniformly at random:

        start ~ Uniform(0, len(ep) - num_steps)

    This two-level scheme guarantees that every valid (episode, start) pair
    in the buffer has equal probability — no transition is under-sampled
    relative to others regardless of episode length differences.

    Args:
        num_steps (int): Number of consecutive steps per sampled sequence.
    """

    def _episode_weights(
        self,
        valid_episodes: list[tuple[int, Episode]],
        total_episodes: int,
    ) -> list[float]:
        return [float(len(ep) - self.num_steps + 1) for _, ep in valid_episodes]

    def __repr__(self) -> str:
        return f"UniformChunkSampler(num_steps={self.num_steps})"


class RecencyWeightedSampler(TrajectorySampler):
    """
    Recency-biased chunk sampler.

    Prioritizes recently added episodes over older ones, which is useful
    in online Model-Based RL to focus training on rollouts generated by
    the latest policy.

    The weight of each episode is:

        weight(ep_i) = (len(ep_i) - num_steps + 1) * exp(recency_factor * (i / N))

    where `i` is the index from oldest (0) to newest (N - 1) in the buffer.

    Args:
        num_steps (int): Number of consecutive steps per sampled sequence.
        recency_factor (float): Strength of the recency bias. 0.0 gives uniform
                                transition weighting; higher values heavily favor
                                recent episodes.
    """

    def __init__(self, num_steps: int = 50, recency_factor: float = 1.0) -> None:
        super().__init__(num_steps=num_steps)
        self.recency_factor = recency_factor

    def _episode_weights(
        self,
        valid_episodes: list[tuple[int, Episode]],
        total_episodes: int,
    ) -> list[float]:
        denom = max(1, total_episodes - 1)
        return [
            (len(ep) - self.num_steps + 1) * math.exp(self.recency_factor * (i / denom)) for i, ep in valid_episodes
        ]

    def __repr__(self) -> str:
        return f"RecencyWeightedSampler(num_steps={self.num_steps}, recency_factor={self.recency_factor})"
